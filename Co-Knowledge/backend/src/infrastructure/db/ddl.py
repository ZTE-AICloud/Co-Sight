"""运行期动态表的建/删/判存。

这两张表是**运行期动态表**（每个知识库一对），由运行期代码管理。

## ``metadata_`` / ``metadata`` 已**展开成物理列**

这两张表各带一个 JSON 列（向量表 ``metadata_``、chunk 表 ``metadata``）存切片元数据。
6 个键**整个展开成列**（``chunk_index`` / ``source`` / ``content_expand`` /
``chunk_id`` / ``type`` / ``pict_info``）—— JSON 列不再存在，行 ↔ dict 的映射统一走
``store/node_columns.py``（**键序必须与旧 JSON 一致**，否则响应字节会变）。

``pict_info``（图片信息）随图片能力退役，已从展开列与建表模板中移除。

DDL 由本仓单方定义，不再有两个服务同时读写同一批表。

⚠️ **``content_expand`` 不建索引**：它可能存整段正文，而 PostgreSQL 的 btree 单条索引键
上限约 2704 字节 —— 建了会让长正文的 INSERT 直接失败。JOIN 走等值比较，不建索引也不会错。

两类表（文档库与图谱库的 chunk 表**模板分开**）：
* 文档向量表 ``kb_index.doc_<id>_vector``：``id/text/node_id/embedding`` +
  4 个展开列 + 审计列，带 node_id / HNSW 索引；
* 文档 chunk 表 ``kb_index.doc_<id>_chunk``：``id/kb_id/source/text/chunk_id/type``
  + 审计列，**无索引**；
* 图谱 chunk 表 ``kb_index.graph_<id>_chunk``：保留 ``chunk_order`` / ``spilt_type``
  / ``label`` / ``table_name`` / ``table_id`` / ``chunk_index`` 等导入导出契约字段。

**正文去重**：``chunk.text`` 是唯一正文副本；向量表 ``text`` 普通行不写入（NULL）。
``vector.text`` 仍被 LLM 优化行使用（写入生成的问题文本），``content_expand``
指向 chunk 行；读写规则见 ``vector_write_store`` 与 ``chunk_store`` 的注释。
"""

from __future__ import annotations

import os
import re

from infrastructure.db.identifiers import SCHEMA, validate_identifier
from infrastructure.db.kb import connection
from infrastructure.logging.logutil import log

#: 未显式给维度时的回落值（与 deploy/.env 的 EMBEDDING_DIMENSION 默认一致）。
DEFAULT_VECTOR_DIMENSION = 1024

#: pgvector 的 HNSW 索引对 ``vector`` 类型的维度上限是 2000。超过时仍可建
#: ``vector(N)`` 列并用 ``<=>`` 精确扫描，但不能建 HNSW —— 建表时跳过索引，
#: 检索走顺序扫描（小库可接受；大库应换 halfvec 或降维）。
HNSW_MAX_DIMENSIONS = int(os.environ.get('RKB_HNSW_MAX_DIMENSIONS', '2000') or 2000)

# 向量表：注意 ``text`` 是保留字要加引号；``id`` 是 GENERATED ... AS IDENTITY。
# ``embedding`` 必须带维度：pgvector 的 HNSW/IVFFlat 拒绝在无维度列上建索引
# （``column does not have dimensions``）。每个知识库只用一个 embedding 模型，
# 所以每张表固定一个维度；跨维度不会混进同一张表。
_SET_UPDATED_AT_FUNCTION = """
CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;
"""

_CREATE_VECTOR_TABLE = _SET_UPDATED_AT_FUNCTION + """
CREATE TABLE IF NOT EXISTS {schema}.{table} (
    id INT8 GENERATED BY DEFAULT AS IDENTITY,
    "text" text   NULL,
    node_id VARCHAR NOT NULL,
    embedding vector({dimension}) NULL,
    source VARCHAR(255) NULL,
    content_expand TEXT NULL,
    chunk_id INT4 NULL,
    type SMALLINT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT {table}_pkey PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS {table}_node_id_uidx ON {schema}.{table} (node_id);
CREATE OR REPLACE TRIGGER {table}_set_updated_at
    BEFORE UPDATE ON {schema}.{table}
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
"""

_VECTOR_HNSW_INDEX = '''
CREATE INDEX IF NOT EXISTS {table}_embedding_hnsw
    ON {schema}.{table} USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);
'''

_DROP_TABLE = 'DROP TABLE IF EXISTS {schema}.{table};'

#: 文档库切片表：只保留活列。图谱库切片表见 ``_CREATE_GRAPH_CHUNK_TABLE`` ——
#: ``chunk_order`` / ``spilt_type`` / ``label`` / ``table_name`` / ``table_id``
#: 是图谱导入/导出契约字段，文档库从不写它们。
_CREATE_CHUNK_TABLE = _SET_UPDATED_AT_FUNCTION + """
CREATE TABLE IF NOT EXISTS {schema}.{table} (
    id VARCHAR(100) NOT NULL,
    kb_id VARCHAR(100) NOT NULL,
    source VARCHAR(255) NULL,
    text TEXT NULL,
    chunk_id INT4 NULL,
    type SMALLINT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT {table}_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS {table}_source_idx ON {schema}.{table} (source);
CREATE OR REPLACE TRIGGER {table}_set_updated_at
    BEFORE UPDATE ON {schema}.{table}
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
"""

_CREATE_GRAPH_CHUNK_TABLE = _SET_UPDATED_AT_FUNCTION + """
CREATE TABLE IF NOT EXISTS {schema}.{table} (
    id VARCHAR(100) NOT NULL,
    kb_id VARCHAR(100) NOT NULL,
    source VARCHAR(255) NULL,
    chunk_order INT4 NULL,
    spilt_type VARCHAR(50) NULL,
    text TEXT NULL,
    label VARCHAR(255) NULL,
    table_name VARCHAR(255) NULL,
    table_id VARCHAR(255) NULL,
    chunk_index VARCHAR(64) NULL,
    content_expand TEXT NULL,
    chunk_id INT4 NULL,
    type SMALLINT NULL,
    created_by VARCHAR(200) NULL,
    updated_by VARCHAR(200) NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT {table}_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS {table}_source_idx ON {schema}.{table} (source);
CREATE OR REPLACE TRIGGER {table}_set_updated_at
    BEFORE UPDATE ON {schema}.{table}
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
"""


def ensure_schema() -> None:
    """``CREATE SCHEMA IF NOT EXISTS kb_index``（幂等）。

    空卷启动时 schema 不存在，``CREATE TABLE kb_index.x`` / ``DROP TABLE
    IF EXISTS kb_index.x`` 都会报 ``schema does not exist`` —— 先建 schema
    是空库可用的前提。
    """
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute('CREATE SCHEMA IF NOT EXISTS kb_index')


_VECTOR_DIMENSION_SQL = """
SELECT format_type(a.atttypid, a.atttypmod)
FROM pg_attribute a
WHERE a.attrelid = to_regclass(%s)
  AND a.attname = 'embedding'
  AND NOT a.attisdropped
"""

_VECTOR_TYPE_PATTERN = re.compile(r'^vector\((\d+)\)$')


def parse_vector_dimension(type_text) -> int | None:
    """``vector(1024)`` → ``1024``；``vector``（无维度）、空值、其它类型 → ``None``。"""
    match = _VECTOR_TYPE_PATTERN.match(str(type_text or '').strip().lower())
    return int(match.group(1)) if match else None


def vector_dimension(table_name: str) -> int | None:
    """``kb_index.<table>.embedding`` 的维度；表/列不存在或读不到 → ``None``。

    这是**唯一可信的维度真值**：``kb_storage_registry.embedding_dim`` 是建库时尽力而为
    的记录，图谱导入的库压根不在其中、旧行也可能是 NULL。
    读不到一律返回 ``None``，由调用方按「无法判定」处理（放行，而不是判死）。
    """
    try:
        validate_identifier(table_name)
        with connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(_VECTOR_DIMENSION_SQL, (f'{SCHEMA}.{table_name}',))
                row = cursor.fetchone()
    except Exception:                                              # noqa: BLE001
        # 画布里的名字是客户端给的：非法标识符/表不存在/库抖动都只意味着「无法判定」
        log.warning('read vector dimension failed for %s.%s', SCHEMA, table_name,
                    exc_info=True)
        return None
    return parse_vector_dimension(row[0] if row else None)


def table_exists(table_name: str) -> bool:
    """``isTableExist``：schema 固定 ``kb_index``。"""
    validate_identifier(table_name)
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                'SELECT EXISTS (SELECT 1 FROM information_schema.tables '
                'WHERE table_schema = %s AND table_name = %s)',
                (SCHEMA, table_name),
            )
            return bool(cursor.fetchone()[0])


def create_vector_table(table_name: str, dimension: int | None = None) -> bool:
    """建向量表。已存在则跳过（与 向量索引 DAO 的 ``createTable`` 的先判存一致）。

    :param dimension: embedding 维度；省略时回落 ``DEFAULT_VECTOR_DIMENSION``。
        列必须带维度，否则 pgvector 无法建 HNSW 索引。
    :return: 是否真的建了
    """
    validate_identifier(table_name)
    if table_exists(table_name):
        return False
    dim = int(dimension or DEFAULT_VECTOR_DIMENSION)
    if dim <= 0:
        raise ValueError(f'illegal vector dimension: {dimension!r}')
    ensure_schema()
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(_CREATE_VECTOR_TABLE.format(
                schema=SCHEMA, table=table_name, dimension=dim))
            if dim <= HNSW_MAX_DIMENSIONS:
                cursor.execute(_VECTOR_HNSW_INDEX.format(
                    schema=SCHEMA, table=table_name))
            else:
                log.warning(
                    'vector dimension %s exceeds HNSW limit %s; table %s.%s '
                    'created without HNSW (exact scan)',
                    dim, HNSW_MAX_DIMENSIONS, SCHEMA, table_name)
    log.info('created vector table %s.%s (dim=%s, hnsw=%s)', SCHEMA, table_name,
             dim, dim <= HNSW_MAX_DIMENSIONS)
    return True


def create_chunk_table(table_name: str) -> bool:
    """建**文档库** chunk 表（活列 + 审计列）。同样先判存。"""
    validate_identifier(table_name)
    if table_exists(table_name):
        return False
    ensure_schema()
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(_CREATE_CHUNK_TABLE.format(schema=SCHEMA, table=table_name))
    log.info('created chunk table %s.%s', SCHEMA, table_name)
    return True


def create_graph_chunk_table(table_name: str) -> bool:
    """建**图谱库** chunk 表（保留导入/导出契约字段）。同样先判存。"""
    validate_identifier(table_name)
    if table_exists(table_name):
        return False
    ensure_schema()
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(_CREATE_GRAPH_CHUNK_TABLE.format(schema=SCHEMA, table=table_name))
    log.info('created graph chunk table %s.%s', SCHEMA, table_name)
    return True


def drop_table(table_name: str) -> None:
    """``DROP TABLE IF EXISTS`` —— 幂等，表不存在也不报错。"""
    validate_identifier(table_name)
    ensure_schema()
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(_DROP_TABLE.format(schema=SCHEMA, table=table_name))
    log.info('dropped table %s.%s', SCHEMA, table_name)


def delete_by_node_ids(vector_table: str, node_ids: list[str]) -> None:
    """按 node_id 批量删向量行。"""
    if not node_ids:
        return
    validate_identifier(vector_table)
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                f'DELETE FROM {SCHEMA}.{vector_table} WHERE node_id = ANY(%s)',
                (list(node_ids),),
            )


def delete_chunks_by_source(chunk_table: str, sources: list[str]) -> int:
    """按 ``source``（文件名）删 chunk 行。

    表不存在时返回 0。
    """
    if not sources:
        return 0
    validate_identifier(chunk_table)
    if not table_exists(chunk_table):
        return 0
    with connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                f'DELETE FROM {SCHEMA}.{chunk_table} WHERE source = ANY(%s)',
                (list(sources),),
            )
            return cursor.rowcount
